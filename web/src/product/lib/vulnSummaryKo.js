/** 요약 칸에 들어가는 짧은 한글 문안. 사전에 없으면 원문을 그대로 쓴다. */
export function vulnSummaryText(item) {
  return VULN_SUMMARY_KO[item?.id]?.short ?? item?.summary ?? '';
}

/**
 * 커서를 올렸을 때의 전문. 한글 설명 뒤에 원문을 함께 남긴다 — 화면의 문장은
 * 우리가 쓴 것이고, 원문이 근거라는 사실이 추적 가능해야 한다.
 */
export function vulnSummaryTitle(item) {
  const detail = VULN_SUMMARY_KO[item?.id]?.detail;
  if (!detail) return item?.summary ?? '';
  return item?.summary ? `${detail}\n\n원문: ${item.summary}` : detail;
}
